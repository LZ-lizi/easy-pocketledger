    LedgerIcon.PLUS -> R.drawable.ic_ledger_plus
    LedgerIcon.SETTINGS -> R.drawable.ic_ledger_settings
    LedgerIcon.CHEVRON_RIGHT -> R.drawable.ic_ledger_chevron_right
    LedgerIcon.ELLIPSIS -> R.drawable.ic_ledger_ellipsis
    LedgerIcon.SEARCH -> R.drawable.ic_ledger_search
    LedgerIcon.FOOD -> R.drawable.ic_ledger_food
    LedgerIcon.TRANSPORT -> R.drawable.ic_ledger_transport
    LedgerIcon.SHOPPING -> R.drawable.ic_ledger_shopping
    LedgerIcon.HOME -> R.drawable.ic_ledger_home
    LedgerIcon.COMMS -> R.drawable.ic_ledger_comms
    LedgerIcon.STUDY -> R.drawable.ic_ledger_study
    LedgerIcon.CAMPUS -> R.drawable.ic_ledger_campus
