    LedgerIcon.WECHAT -> R.drawable.ic_ledger_wechat
    LedgerIcon.TAG -> R.drawable.ic_ledger_tag
}

/** One tinted glyph at [size]; the single entry point every screen uses. */
@Composable
fun LedgerIconView(
    icon: LedgerIcon,
    tint: Color,
    modifier: Modifier = Modifier,
    size: Dp = 24.dp,
) {
    Icon(
        painter = painterResource(icon.drawable()),
        contentDescription = null,
        tint = tint,
        modifier = modifier.size(size),
    )
}
